// 미수 읽는 계약의 «열쇠 규칙» — JSON Schema 로는 칸끼리 맞는지 못 본다.
//
// ★Codex 검토(2026-09-29, PR #343): 「키와 법인·차번·계약상태·계약ID 가 어긋나도 통과한다」.
//   키가 다른 칸과 따로 놀면 같은 차가 두 문서가 되는 병(put-galrae 2칸 문서)이 모양만 바꿔 돌아온다.
//   그래서 키는 적힌 값을 믿지 않고 다른 칸에서 «만들어 본 값»과 같아야 한다.

/** 다른 칸에서 키를 만든다. 만들 수 없으면(종료인데 계약ID 없음 등) null. */
export function 키만들기({ 법인, 차량번호, 계약상태, 계약ID }) {
  if (!법인 || !차량번호) return null;
  if (계약상태 === 'live') return `${법인}-${차량번호}-live`;
  if (계약상태 === 'end') return 계약ID ? `${법인}-${차량번호}-end-${계약ID}` : null;
  return null;
}

/** 문서의 키가 다른 칸과 맞나. 맞으면 [], 아니면 까닭 목록. */
export function 키검사(문서) {
  const 기대 = 키만들기(문서);
  if (기대 === null) return ['키를 만들 수 없다 — 법인·차량번호·계약상태(종료면 계약ID)가 모자란다'];
  if (문서.키 !== 기대) return [`키 «${문서.키}» 가 다른 칸에서 만든 «${기대}» 와 다르다`];
  return [];
}
