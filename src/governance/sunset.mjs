// «지워질 자리»가 실제로 줄고 있는지 잰다.
//
// ★대표 2026-09-29: 「통합해서 개발센터·aiops·문서허브 폴더 다 삭제하는 거야 … 삭제할 수 있는 준비를 하자고」
//
//   lane 지도는 이 폴더들을 «소유»로 적었다. 종착역이 삭제라면 그건 소유가 아니라 **일몰 구역**이다.
//   소유는 「누가 고치나」를 묻지만, 일몰은 「언제 없어지나」를 묻는다. 재는 것이 다르다.
//
//   지울 수 있으려면 둘이 필요하다:
//     ① 보존  — 내용이 다른 곳에 살아 있다
//     ② 참조 0 — 바깥에서 아무도 이 자리를 가리키지 않는다
//   ②가 이 파일의 일이다. 참조가 남아 있는데 지우면 그건 정리가 아니라 고장이다.

/** ★«끌어 쓴다»는 코드가 하는 일이다. JSON 은 기록이지 의존이 아니다.
 *
 *  처음엔 .json 도 끌어씀으로 셌더니 `catalog/index.json` 같은 «목록 파일»이
 *  의존처럼 잡혔다(실측 2026-09-29). 그런 건 지워도 아무것도 안 깨진다 — 언급으로 센다.
 *  혹시 경로 설정을 담은 JSON 이 있어도 언급에 남아 0 이 되어야 하므로 놓치지 않는다. */
const 코드파일 = /\.(mjs|js|cjs|ts|mts|tsx|jsx|ps1|cmd|sh|py)$/i;

/**
 * 일몰 구역을 가리키는 곳을 센다.
 *
 * ★«일몰끼리»의 참조는 막는 것으로 세지 않는다 — 같이 사라질 것들이라 서로를 붙잡지 않는다.
 *   aiops/ 가 devcenter/ 를 부르는 것은 둘 다 없어지면 함께 사라진다.
 *   이걸 안 가르면 영원히 0 이 안 되고, 그러면 기준선이 아무 뜻도 없다.
 *
 * @param 파일들   {path, text} 전체
 * @param 구역     'aiops/' 처럼 끝에 / 가 붙은 경로 앞머리
 * @param 모든구역 일몰 구역 전부 — 이 안에서 온 참조는 «일몰끼리»로 따로 센다
 */
export function 참조찾기(파일들, 구역, 모든구역 = [구역], 자기파일 = [], 기록접두사 = []) {
  const 이름 = 구역.replace(/\/$/, '');
  /** 끌어 쓰기 — import/require/실행 경로처럼 «없으면 깨지는» 자리. */
  const 끌기 = new RegExp(`(?:from\\s+['"\`]|require\\(\\s*['"\`]|import\\(\\s*['"\`]|node\\s+|--root\\s+|['"\`])[^'"\`\\s]*${이름}/`);
  const 부르기 = new RegExp(`${이름}/`);

  const 끌어씀 = [];
  const 언급 = [];
  const 일몰끼리 = [];
  for (const { path, text } of 파일들) {
    if (path.startsWith(구역)) continue;
    /** ★재는 도구는 재는 대상에 안 잡힌다. 이 파일들은 구역 «이름을 선언»할 뿐 끌어 쓰지 않는다. */
    if (자기파일.includes(path)) continue;
    /** ★물어본 것이 붙잡는 것이 될 수는 없다 — 우편함 쪽지는 기록이지 의존이 아니다. */
    if (기록접두사.some((p) => path.startsWith(p))) continue;
    if (!부르기.test(text)) continue;
    if (모든구역.some((다른) => 다른 !== 구역 && path.startsWith(다른))) { 일몰끼리.push(path); continue; }
    (코드파일.test(path) && 끌기.test(text) ? 끌어씀 : 언급).push(path);
  }
  return { 끌어씀, 언급, 일몰끼리 };
}

/**
 * 일몰 구역 하나의 «삭제 준비도».
 *
 * ★기준선은 내려가기만 한다. 브랜치 흐름에 건 것과 같은 톱니(ratchet)다 —
 *   올릴 수 있으면 「통합 중」이라는 말이 아무 뜻도 없어진다.
 */
export function 준비도(구역설정, 파일들, 구역파일수, 모든구역 = [구역설정.path], 자기파일 = [], 기록접두사 = []) {
  const { 끌어씀, 언급, 일몰끼리 } = 참조찾기(파일들, 구역설정.path, 모든구역, 자기파일, 기록접두사);
  const 넘음 = {
    끌어씀: Math.max(0, 끌어씀.length - 구역설정.baseline.끌어씀),
    언급: Math.max(0, 언급.length - 구역설정.baseline.언급)
  };
  return {
    구역: 구역설정.path,
    파일수: 구역파일수,
    끌어씀: 끌어씀.length,
    언급: 언급.length,
    기준선: 구역설정.baseline,
    넘음,
    지울수있나: 끌어씀.length === 0 && 구역설정.preserved === true,
    일몰끼리: 일몰끼리.length,
    막는것: 끌어씀.slice(0, 5)
  };
}
