import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import assert from 'node:assert/strict';
import {inspectProject} from './inspect-project.mjs';

const fixture=fs.mkdtempSync(path.join(os.tmpdir(),'devcenter-inspection-'));
const run=(args)=>{const r=spawnSync('git',args,{cwd:fixture,encoding:'utf8',windowsHide:true});assert.equal(r.status,0,r.stderr)};
try{
 run(['init','-q']);
 fs.writeFileSync(path.join(fixture,'AGENTS.md'),'# fixture rules\n');
 fs.writeFileSync(path.join(fixture,'package.json'),JSON.stringify({scripts:{build:'echo build',test:'echo test',typecheck:'echo types'}}));
 fs.writeFileSync(path.join(fixture,'.env.local'),'TOKEN=fixture-value-that-must-not-appear');
 run(['add','AGENTS.md','package.json','.env.local']);
 const lockPath=spawnSync('git',['rev-parse','--git-path','index.lock'],{cwd:fixture,encoding:'utf8',windowsHide:true}).stdout.trim();fs.writeFileSync(path.resolve(fixture,lockPath),'fixture');
 const unsafe=inspectProject(fixture);
 assert.equal(unsafe.summary.overall,'FAIL');
 assert.equal(unsafe.checks.find(c=>c.id==='GOV-SECRET-001')?.status,'FAIL');
 assert.equal(unsafe.checks.find(c=>c.id==='GOV-LOCK-001')?.status,'HOLD');
 assert(!JSON.stringify(unsafe).includes('fixture-value-that-must-not-appear'));
 fs.unlinkSync(path.resolve(fixture,lockPath));
 run(['rm','--cached','-q','.env.local']);
 fs.unlinkSync(path.join(fixture,'.env.local'));
 const safer=inspectProject(fixture);
 assert.equal(safer.checks.find(c=>c.id==='GOV-SECRET-001')?.status,'PASS');
 assert.equal(safer.checks.find(c=>c.id==='GOV-RULE-001')?.status,'PASS');
 assert.equal(safer.checks.find(c=>c.id==='GOV-CHECK-001')?.status,'PASS');
 const malformed=path.join(fixture,'acceptance-bad.json');fs.writeFileSync(malformed,JSON.stringify({passed:999,total:50,average:1998,basic:{passed:999,total:40},deep:{passed:0,total:10},areas:[],overallReview:'PASS'}));
 const badEvidence=inspectProject(fixture,{acceptancePath:malformed});
 assert.equal(badEvidence.checks.find(c=>c.id==='GOV-EVIDENCE-001')?.status,'HOLD');
 assert.equal(badEvidence.checks.find(c=>c.id==='GOV-REVIEW-001')?.status,'HOLD');
 const forgedAreas=Array.from({length:5},(_,area)=>({total:10,passed:10,percentage:100,criteria:Array.from({length:10},(_,item)=>({id:`X${area}-${item}`,status:'PASS',deep:area===4}))}));
 fs.writeFileSync(malformed,JSON.stringify({passed:50,total:50,average:100,basic:{passed:999,total:40},deep:{passed:-949,total:10},areas:forgedAreas,overallReview:'PASS'}));
 const impossibleSplit=inspectProject(fixture,{acceptancePath:malformed});
 assert.equal(impossibleSplit.checks.find(c=>c.id==='GOV-EVIDENCE-001')?.status,'HOLD');
 assert.equal(impossibleSplit.checks.find(c=>c.id==='GOV-REVIEW-001')?.status,'HOLD');
 fs.writeFileSync(path.join(fixture,'.git','index'),'corrupt index');
 const unreadableGit=inspectProject(fixture);
 assert.equal(unreadableGit.checks.find(c=>c.id==='GOV-WORKTREE-001')?.status,'HOLD');
 assert.equal(unreadableGit.checks.find(c=>c.id==='GOV-SECRET-001')?.status,'HOLD');
 const current=inspectProject(path.resolve('.'));
 assert.equal(current.kind,'devcenter_inspection_report_v1');
 assert.equal(current.summary.total,current.checks.length);
 assert.equal(current.checks.find(c=>c.id==='GOV-SSOT-001')?.status,'PASS');
 console.log(`PASS: inspection fixture caught tracked secret name and Git lock without reading secret values; current devcenter produced ${current.checks.length} evidence-backed checks.`);
}finally{
 const tmp=path.resolve(os.tmpdir())+path.sep,target=path.resolve(fixture);
 if(target.startsWith(tmp))fs.rmSync(target,{recursive:true,force:true});
}
