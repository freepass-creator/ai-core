/** ★★★행정구역 «절대값» 에 붙인다 — 대표(2026-09-01)
 *    「중구 강서구 이렇게만 잡으면 안 되지. 그 데이터를 **헷갈림 없는 데이터를 만들어 놔야지**.
 *     ★**일단 절대값을 만들어 놓고 거기에 붙여야지**」
 *
 *  ── ★왜 절대값인가
 *  앞서 「중구」 · 「강서구」 를 하나씩 손으로 막았다. 그러면 끝이 없다 —
 *  동구·서구·남구·북구·고성군… 겹치는 이름이 수십이다.
 *  ★나라의 행정구역은 «정해져 있다». 그 표를 두고 «맞춰» 보면 헷갈릴 일이 없다.
 *    겹치면 «겹친다» 고 말해 주면 된다 — 그게 사실이니까.
 *
 *  ── 절대값은 `lib/wonja/행정구역.json` 이다
 *      시도 17 · 자치구 69 · 시 77 · 군 82 (기초 228) · 일반구 32
 *  ★틀린 것이 있으면 «그 파일» 을 고친다. 도구에 박지 않는다.
 *
 *  ── 무엇을 돌려주나
 *      { 온전한이름, 시도, 기초, 일반구, 겹침 }
 *  ★한 곳이면 온전한 이름. 여러 곳이면 `겹침` 에 다 담고 이름은 null.
 *    ★null 을 채우려 지어내지 않는다.
 */
import fs from 'node:fs';

const 길 = new URL('./wonja/행정구역.json', import.meta.url);
const 표 = JSON.parse(fs.readFileSync(길, 'utf8'));
const 붙 = (v) => String(v ?? '').replace(/\s+/g, '').trim();

/** ★한 번만 차린다 — 고지서마다 다시 세우면 느리다 */
const 판 = (() => {
  /** 열쇠 → [{ 시도, 기초, 일반구, 온전한이름 }] */
  const 표기 = new Map();
  const 넣 = (열쇠, 값) => {
    const k = 붙(열쇠); if (!k) return;
    if (!표기.has(k)) 표기.set(k, []);
    const 있 = 표기.get(k);
    if (!있.some((x) => x.온전한이름 === 값.온전한이름)) 있.push(값);
  };
  const 시도줄임 = new Map();

  for (const [시도, x] of Object.entries(표.시도)) {
    const 짧들 = [시도, ...(x.줄임 ?? [])];
    for (const s of 짧들) 시도줄임.set(붙(s), 시도);
    /** ★시도 그 자체 (세종·제주처럼 기초가 없거나 도청이 부과하는 곳) */
    for (const s of 짧들) 넣(s, { 시도, 기초: null, 온전한이름: 시도 });

    /** ★제주 「행정시」 도 열쇠로 넣는다 — 기초자치단체는 아니지만 고지서는 거기서 온다 */
    for (const 갈래 of ['구', '시', '군', '★행정시']) {
      for (const 기초 of x[갈래] ?? []) {
        const 온전 = `${시도} ${기초}`;
        const 민 = 기초.replace(/[구시군]$/, '');   /** 「강서구」 → 「강서」 */
        /** ★열쇠를 넉넉히 — 사람과 OCR 이 여러 꼴로 적는다 */
        for (const s of 짧들) {
          넣(`${s}${기초}`, { 시도, 기초, 온전한이름: 온전 });
          넣(`${s}${민}`, { 시도, 기초, 온전한이름: 온전 });
        }
        /** ★시도 없이 기초만 — 겹치면 여럿이 담긴다. 그게 사실이다 */
        넣(기초, { 시도, 기초, 온전한이름: 온전 });
        넣(민, { 시도, 기초, 온전한이름: 온전 });
      }
    }
  }
  /** ★일반구 — 「수원시 권선구」 */
  for (const [시, 구들] of Object.entries(표['★일반구'].것)) {
    /** 그 시가 어느 시도인가 */
    const 시도 = Object.entries(표.시도).find(([, x]) => (x.시 ?? []).includes(시))?.[0] ?? null;
    const 민시 = 시.replace(/시$/, '');
    for (const 구 of 구들) {
      const 민구 = 구.replace(/구$/, '');
      const 온전 = `${시} ${구}`;
      for (const a of [시, 민시]) for (const b of [구, 민구]) 넣(`${a}${b}`, { 시도, 기초: 시, 일반구: 구, 온전한이름: 온전 });
      /** ★일반구 이름만 — 「기흥」 처럼 한 곳에만 있으면 잡힌다 */
      넣(구, { 시도, 기초: 시, 일반구: 구, 온전한이름: 온전 });
      넣(민구, { 시도, 기초: 시, 일반구: 구, 온전한이름: 온전 });
    }
  }
  return { 표기, 시도줄임 };
})();

/** ★★2026-07-01 «전» 이름 — 우리 고지서는 개편 전후가 섞여 있다.
 *  ★대표(2026-09-01): 「전국에 시군구청 과태료 부과 데는 네가 뽑아낼 수 있잖아 … 웹서치가 더 빠르겠다」
 *    ★웹에서 확인했더니 내 표가 «두 군데 틀려» 있었다:
 *      광주광역시 + 전라남도 → 전남광주통합특별시 (2026-07-01)
 *      인천 중구·동구 폐지 → 제물포구·영종구 · 서구 → 서해구·검단구 (2026-07-01)
 *  ★옛 이름으로도 찾히게 두되 «이어받은 곳» 을 같이 낸다. 공문은 이어받은 곳으로 간다 */
const 옛이름표 = (() => {
  const m = new Map();
  for (const [옛, x] of Object.entries(표['★옛 이름']?.것 ?? {})) m.set(붙(옛), { 옛이름: 옛, ...x });
  return m;
})();

/** ★옛 이름인가 — 맞으면 이어받은 곳을 낸다 */
export function 옛이름찾기(이름) {
  const ㄱ = 붙(이름);
  const 곧 = 옛이름표.get(ㄱ);
  if (곧) return 곧;
  /** ★「인천중구」 처럼 붙여 쓴 것도 잡는다 */
  for (const [k, v] of 옛이름표) {
    const 씻k = k.replace(/(특별자치시|특별자치도|특별시|광역시)/g, '');
    if (씻k === ㄱ || k === ㄱ) return v;
  }
  return null;
}

/** ★그 시에 일반구가 있나 — 있으면 «구청» 이 부과한다 */
export const 일반구있나 = (시) => Boolean(표['★일반구'].것[붙(시)] ?? 표['★일반구'].것[`${붙(시)}시`]);
export const 일반구들 = (시) => 표['★일반구'].것[붙(시)] ?? 표['★일반구'].것[`${붙(시)}시`] ?? [];

/**
 * ★이름 조각을 «절대값» 에 맞춘다.
 *
 *   찾기('강서구')        → 겹침 2 (서울특별시 강서구 · 부산광역시 강서구)
 *   찾기('서울강서')      → 서울특별시 강서구
 *   찾기('수원권선')      → 수원시 권선구
 *   찾기('김포')          → 경기도 김포시
 *   ★못 찾으면 { 온전한이름: null }
 */
export function 찾기(이름) {
  const ㄱ = 붙(이름);
  if (!ㄱ) return { 온전한이름: null, 겹침: [], 왜: '이름이 없다' };

  /** ★① 그대로 있나 — 열쇠를 넉넉히 넣어 두었으니 여기서 거의 끝난다 */
  const 곧 = 판.표기.get(ㄱ);
  if (곧?.length === 1) return { ...곧[0], 겹침: [], 왜: '절대값에 하나뿐' };
  if (곧?.length > 1) {
    /** ★★시도 이름 그 자체면 «시도» 다 — 「제주」 는 제주특별자치도이지 제주시가 아니다.
     *  ★2026-09-01: 「제주교통행정」 이 제주도 ↔ 제주시로 겹쳐 못 붙었다.
     *    도청 교통행정과가 부과하는 것이고, 제주시청이면 「제주시」 라 적힌다 */
    if (판.시도줄임.has(ㄱ)) {
      const 시도 = 판.시도줄임.get(ㄱ);
      const 그것 = 곧.find((x) => !x.기초 && x.시도 === 시도);
      if (그것) return { ...그것, 겹침: [], 왜: '시도 이름 그 자체' };
    }
    return { 온전한이름: null, 겹침: 곧, 왜: `★${곧.length}곳에 있다 — ${곧.map((x) => x.온전한이름).join(' · ')}` };
  }

  /** ★② 꼬리를 걷고 다시 — 「강서구청장」 · 「김포시청」 · 「연천군수」 */
  const 벗 = ㄱ.replace(/(구청장|구청|시청장|시청|군청장|군청|시장|군수|청장|청)$/, '');
  if (벗 && 벗 !== ㄱ) {
    const r = 판.표기.get(벗) ?? 판.표기.get(`${벗}구`) ?? 판.표기.get(`${벗}시`) ?? 판.표기.get(`${벗}군`);
    if (r?.length === 1) return { ...r[0], 겹침: [], 왜: '꼬리를 걷으니 하나뿐' };
    if (r?.length > 1) return { 온전한이름: null, 겹침: r, 왜: `★${r.length}곳에 있다 — ${r.map((x) => x.온전한이름).join(' · ')}` };
  }

  /** ★③ 시도가 앞에 붙어 있나 — 「서울특별시강서」 처럼 */
  for (const [짧, 시도] of 판.시도줄임) {
    if (!ㄱ.startsWith(짧) || ㄱ === 짧) continue;
    const 뒤 = ㄱ.slice(짧.length).replace(/(구청장|구청|시청|군청|시장|군수)$/, '');
    const r = (판.표기.get(뒤) ?? []).filter((x) => x.시도 === 시도);
    if (r.length === 1) return { ...r[0], 겹침: [], 왜: `시도 「${시도}」 로 가려짐` };
  }

  /** ★④ 2026-07-01 «전» 이름인가 */
  const 옛 = 옛이름찾기(ㄱ) ?? 옛이름찾기(ㄱ.replace(/(구청장|구청|시청|군청|시장|군수)$/, ''));
  if (옛) {
    const 이어 = 옛.이어받은곳 ?? [];
    return {
      온전한이름: 이어.length === 1 ? 이어[0] : null,
      옛이름: 옛.옛이름, 이어받은곳: 이어, 겹침: [],
      왜: 이어.length === 1
        ? `★2026-07-01 에 「${옛.옛이름}」 이 「${이어[0]}」 으로 이어졌다`
        : `★2026-07-01 에 「${옛.옛이름}」 이 «둘로 갈렸다» — ${이어.join(' · ')}. ${옛['★둘로 갈렸다'] ?? ''}`,
    };
  }

  return { 온전한이름: null, 겹침: [], 왜: '★절대값에 없다 — 지자체가 아니거나 이름이 너무 뭉갰다' };
}
