export const 딱지 = { 접수함: '올리는곳', 발송전: '발송할것', 확인필요: '확인할것', 낸것: '완료한것' };

/** ★옛 딱지 — 드라이브에 아직 남아 있을 수 있는 이름들. 찾을 때는 이것도 본다 */
export const 옛딱지 = ['발송대기', '검토중', '발송전', '문서24에낼것', '보낼것', '확인필요', '처리완료'];

/** ★공문 파일 이름의 꼴 —  [딱지] 관청_법인_N건_YYYYMMDD.pdf
 *  ★1=딱지 · 2=관청(수신처) · 3=법인 · 4=건수 */
export function 공문꼴() {
  const B = String.fromCharCode(92);          // ★역슬래시 — heredoc 이 먹어서 이렇게 짓는다
  const 것 = [...new Set([...Object.values(딱지), ...옛딱지])].join('|');
  return new RegExp(`^${B}[(${것})${B}]${B}s*(.+?)_([^_]+)_([0-9]+)건_[0-9]{8}`);
}

/** ★★★자리 안의 파일을 «하위 폴더까지» 다 센다 — 2026-09-03
 *
 *  ── ★왜 필요해졌나
 *  대표(2026-09-03): 「발송할것 폴더에 법인별로만 폴더 모아주라」
 *  ★그래서 「2 발송할것」 아래 법인 폴더가 생겼다 — 손오공렌터카·스위치플랜·프라임구독…
 *  ★그런데 도구 다섯이 «맨 위만» 보고 있었다:
 *      겹침 치우기 · 유령 원장 치우기 · 내기전점검 · 법인별 모으기 · 이미낸것 가리기
 *  ★그러면 법인 폴더 «안» 의 공문이 다 「없는 것」 이 된다 —
 *    겹침이 안 치워지고, 원장이 유령으로 잡히고, 점검이 「0장」 이라 한다.
 *  ★★조용히 0 이 되는 자리다. 폴더 하나 만들었다고 도구 다섯이 눈이 머는 것이다.
 *
 *  ★그래서 «한 곳» 에 둔다. 도구는 이걸 부른다.
 *    깊이는 2 까지 — 법인 폴더 아래 또 폴더를 두지 않는다.
 */
export async function 자리안파일들(d, 이름, { 깊이 = 2 } = {}) {
  /** ★★★`d.ls()` 는 «파일만» 준다 — 폴더는 `d.subs()` 로 따로 받아야 한다 (2026-09-03)
   *  ★처음에 ls 가 폴더도 주는 줄 알고 mimeType 으로 걸렀다. 그래서 하위를 «한 곳도» 안 들어갔다.
   *    발송할것에 114장이 있는데 「3장」 만 보였고, 공문꼴에 맞는 것이 「0장」 이 됐다.
   *  ★★또 «조용히 0» 이다. 이 병만 오늘 네 번째다. */
  const 나온것 = [];
  const 본폴더 = new Set();
  const 훑기 = async (id, 어디, 남은) => {
    if (!id || 본폴더.has(id)) return;
    본폴더.add(id);
    for (const x of await d.ls(id)) 나온것.push({ ...x, 어디 });
    if (남은 > 1) for (const s of await d.subs(id)) await 훑기(s.id, s.name, 남은 - 1);
  };
  for (const f of 폴더들(이름)) await 훑기(f.id, '(맨 위)', 깊이);
  return 나온것;
}
