/** ★★데이터센터 폴더 이름 — «한 곳» 에만 둔다. 옛 이름과 새 이름을 «둘 다» 안다.
 *
 *  ★★규격 자체는 여기 없다 — `lib/올리는곳.json` 의 `폴더규격`이 정본이다 (2026-09-03).
 *
 *  > 대표(2026-09-03): 「그러니까 폴더를 **유연하게** aiops 에서 하려면 어떻게 해야하는데??」
 *
 *  ── ★왜 표로 뺐나
 *  전에는 규격이 «코드 안» 에 박혀 있었다 —
 *    이름표는 이 파일에, 최상위·갈래 목록은 `scripts/폴더점검.mjs` 안에 상수로.
 *  ★그래서 **회사를 하나 늘리거나 잎을 하나 더하려면 «도구를 고쳐야» 했다.** 그게 뻣뻣함의 정체다.
 *
 *  ★이제 표 한 줄만 고치면 된다. 도구는 안 고친다 —
 *      규격을 바꾼다   →  lib/올리는곳.json 을 고친다
 *      맞나 본다      →  node scripts/폴더점검.mjs
 *      실제로 맞춘다   →  node scripts/이름규격.mjs --한다
 *      지도를 굽는다   →  node wonja/build-dc-folders.mjs
 *
 *  ── ★「모든 회사에 똑같이」 와 「이 회사만」 을 표에서 고른다
 *  코덱스는 「잎까지 동일 강제하지 말고 법인별 허용 목록으로」 라 했고,
 *  나는 「잎도 강제한다 — 위약금은 폴더가 없어서 안 쌓였다」 고 했다.
 *  ★이 다툼은 «코드» 가 아니라 «표» 에서 갈린다. 잎마다 이렇게 적는다 —
 *      어디: "모든회사"        01~06 에 다 있어야 한다
 *      어디: ["06_공통"]      그 회사에만 있으면 된다
 *      반드시: false          있어도 되고 없어도 된다
 *
 *  ── ★그래도 이 파일이 남아 있는 까닭
 *  옛 이름을 부르는 코드가 «여든 곳» 이 넘는다. 폴더만 바꾸고 코드를 안 고치면
 *  도구가 죽지 않는다 — «조용히 빈 값을 읽는다». 그게 더 나쁘다.
 *  ★그래서 «찾는 자리 한 곳» 이 옛 이름도 알아듣게 한다. 그 별명을 여기서 만든다.
 */
import { readFileSync } from 'node:fs';

/** ★규격 정본 — 사람이 고치는 자리다 */
/** ★규격 정본 — 사람이 고치는 자리다.
 *  ★★`올리는곳.json` 과 «합치지 않는다» (코덱스 H-20260903-062) —
 *    올리는곳은 「파일을 어디에 둘까(경로)」, 여기는 「그 자리가 있어야 하나(구조)」 다.
 *    바뀌는 빠르기도, 고치는 문턱도 다르다. 대신 `scripts/폴더점검.mjs` 가 둘이 «이어졌나» 를 검사한다. */
export const 규격 = JSON.parse(readFileSync(new URL('./폴더규격.json', import.meta.url), 'utf8'));

const 갈래찾 = (이름) => 규격.갈래.find((g) => g.이름 === 이름);
const 짝 = (잎목) => 잎목.flatMap((x) => (x.옛 ?? []).map((옛) => [옛, x.이름]));

/** ★갈래별 «옛 이름 → 새 이름». 규격은 부모문자 + 두 자리 (A01_ B01_ C01_) */
export const 이름표 = Object.fromEntries(
  ['A_법인', 'B_재무세무', 'C_차량', 'D_인사', 'E_영업', 'F_금융']
    .map((g) => [g, 짝(갈래찾(g)?.잎 ?? [])]),
);

/** ★`C_차량` 에서 «나간» 것 — `G_고지서·채권` 갈래 */
export const 새갈래 = 'G_고지서·채권';
export const 나갈것 = 짝(갈래찾(새갈래)?.잎 ?? []);

/** ★폴더가 없어서 «안 쌓이던» 것. 자리를 먼저 만든다 */
export const 새로만들잎 = (규격['★새로만들잎'] ?? []).map((x) => [x.부모, x.이름]);

/** ★★`Z_기타` 에 떠 있던 「정산」 을 `B07_CMS·카드정산` 으로 들인다 */
export const 들일것 = (규격['합쳐진것'] ?? []).map((x) => ({ 어디: x.어디서, 무엇: x.옛[0], 어디로: 'B_재무세무', 새이름: x.이름 }));

/** ★최상위 — 번호로 차례를 고정한다. ★별표는 남긴다 */
export const 최상위이름표 = [['★★과태료작업★★', '02_★★과태료작업★★']];
export const 과태료안이름표 = 짝(규격['최상위잎']?.['02_★★과태료작업★★'] ?? []);

/** ★★`G` 가 「고지서·채권」 으로 정해져서 「G_JPK문서」 와 부딪친다 — H 로 민다 */
export const 공통이름표 = (갈래찾('H_JPK문서')?.옛 ?? []).map((옛) => [옛, 'H_JPK문서']);

/** ★★«합쳐져서» 이름이 바뀐 것 — 이름표와 갈라 둔다.
 *  이름표는 `scripts/이름규격.mjs` 가 «이름을 바꾸는» 데 쓴다.
 *  ★「정산」 은 이름을 바꾼 게 아니라 «B07 안으로 합쳐졌다». 그래도 «찾을 때» 는 옛 이름으로 물어올 수 있다. */
export const 합쳐진이름 = (규격['합쳐진것'] ?? []).flatMap((x) => x.옛.map((옛) => [옛, x.이름]));

/** ★모든 「옛 → 새」 를 한 줄로 편다 (갈래 안 잎 · 나간 것 · 합쳐진 것 · 최상위 · 과태료 안 · 공통) */
export const 옛에서새로 = new Map([
  ...Object.values(이름표).flat(),
  ...나갈것,
  ...합쳐진이름,
  ...최상위이름표,
  ...과태료안이름표,
  ...공통이름표,
]);
export const 새에서옛으로 = new Map([...옛에서새로].map(([옛, 새]) => [새, 옛]));

/**
 * ★찾을 때 써 볼 이름들 — «지금 이름» 이 맨 앞이다.
 *
 *  옛 이름(`C1_계약서`)으로 물어도 새 이름(`C01_계약서`)을 찾아 주고, 그 반대도 된다.
 *  ★폴더를 바꾸는 동안에도, 다 바꾼 뒤에도 «양쪽 다» 도는 까닭이 이것이다.
 */
export function 별명들(잎) {
  const 새 = 옛에서새로.get(잎);
  const 옛 = 새에서옛으로.get(잎);
  return [...new Set([새 ?? 잎, 잎, 옛].filter(Boolean))];
}

/** 이 잎이 어느 갈래에 속하나 — `C01_계약서` → `C_차량` (없으면 null) */
export function 갈래(잎) {
  const 이름 = 옛에서새로.get(잎) ?? 잎;
  for (const [g, 표] of Object.entries(이름표)) if (표.some(([, 새]) => 새 === 이름)) return g;
  if (나갈것.some(([, 새]) => 새 === 이름)) return 새갈래;
  if (새로만들잎.some(([, 잎이름]) => 잎이름 === 이름)) return 새로만들잎.find(([, 잎이름]) => 잎이름 === 이름)[0];
  return null;
}

/**
 * ★★대장 줄의 「폴더」 가 이 잎인가 — 옛 이름·새 이름을 «둘 다» 맞는다.
 *
 *  ── 왜 이게 따로 있나 (2026-09-03 · 코덱스가 짚었다)
 *  `tmp/문서대장.json` 은 폴더를 «이름 문자열» 로 담는다. 그래서 도구들이 이렇게 걸렀다 —
 *      대장.filter((x) => x.폴더 === 'C1_계약서')
 *  ★잎 이름을 `C01_계약서` 로 바꾸고 대장을 다시 만들면 이 걸림이 «0건» 이 된다.
 *    죽지 않는다. 조용히 빈손으로 돈다. 그게 더 나쁘다.
 *
 *  ★코덱스의 수용기준이 「구 이름 참조 0건」 이었는데, 나는 그걸 못 맞추고 있었다.
 *    id 로 접근하는 곳은 이름을 바꿔도 멀쩡하다 — 그런데 «이름을 키로 쓰는» 대장 코드는 안 그렇다.
 *
 *      import { 같은잎 } from '../lib/폴더이름.mjs';
 *      대장.filter((x) => 같은잎(x.폴더, 'C01_계약서'))
 */
export function 같은잎(대장폴더, 잎) {
  const n = String(대장폴더 ?? '');
  return 별명들(잎).some((x) => x === n);
}
