/** ★사람 이름을 다루는 자리 — «꼬리를 지우지 않는다».
 *
 *  대표(2026-08-28): 「음 **지인대여**거나 그런가. **없을 순 없을 건데**」
 *
 *  ── ★★이 파일이 생긴 까닭
 *  「아직 대여중인데 계약서가 없다」 8건을 뒤졌더니 4건은 **있었다**.
 *  못 찾은 것은 내가 이름을 «너무 씻어서» 였다.
 *
 *      시트 계약자   「정준영3」   ← 동명이인 셋째 사람
 *      내 씻기       「정준영」    ← ★꼬리를 지웠다
 *      그랬더니 「정준영」 계약이 여럿이라 어느 것인지 못 골랐다
 *      ★그런데 파일 이름도 「정준영3.pdf」 다 — 직원이 «같은 꼬리» 를 쓴다
 *
 *  ★꼬리는 «군더더기» 가 아니라 «누구인지» 다. 지우면 사람이 뭉개진다.
 *
 *  ── ★꼬리에 두 갈래가 있다
 *      동명이인 꼬리   김창준a · 김창준b · 정준영3 · 고객1201   (영문 23 · 숫자 95)
 *      ★외국인 이름    ALEKSEY · OLGA · ANJELIKA
 *                      이건 «꼬리가 아니라 이름 그 자체» 다. 지우면 이름이 사라진다
 *
 *  ── ★그래서 «두 가지» 로 견준다
 *      꼬리째    「정준영3」 ↔ 「정준영3」   ★센 짝 — 사람이 확정된다
 *      민이름    「정준영」  ↔ 「정준영」    약한 짝 — 동명이인일 수 있다
 *    ★센 짝이 있으면 그것을 쓰고, 없을 때만 민이름으로 내려간다.
 */

/** 법인 꼬리·괄호만 떼고 «사람 꼬리는 남긴다» */
export function 이름다듬기(v) {
  return String(v ?? '')
    .replace(/\((주)\)|주식회사|㈜/g, '')
    .replace(/\s+/g, '')
    .trim();
}

/** ★꼬리를 뗀 민이름. «동명이인이 뭉개진다» — 마지막에만 쓴다 */
export function 민이름(v) {
  const n = 이름다듬기(v);
  if (/^[A-Za-z]{2,}$/.test(n)) return n.toUpperCase();   // ★외국인 이름은 통째로 이름이다
  return n.replace(/[0-9]+$/, '').replace(/[a-zA-Z]$/, '');
}

/** ★꼬리가 있나 · 무엇인가 */
export function 꼬리(v) {
  const n = 이름다듬기(v);
  if (/^[A-Za-z]{2,}$/.test(n)) return null;              // 외국인 이름 — 꼬리 아님
  const m = n.match(/([0-9]+|[a-zA-Z])$/);
  return m ? m[1] : null;
}

/** ★두 이름이 «같은 사람» 인가 — 얼마나 센지도 말해 준다
 *
 *    '꼬리째'   「정준영3」 ↔ 「정준영3」   ★사람이 확정된다
 *    '민이름'   「고객138」  ↔ 「고객138」    동명이인일 수 있다
 *    '꼬리한쪽' 「정준영3」 ↔ 「정준영」    한쪽만 꼬리가 있다 — 약하다
 *    ★'꼬리다름' 「고객1201」 ↔ 「고객1202」   ★다른 사람이다
 *    ★'꼬리규칙다름' 「김창준b」 ↔ 「김창준2」 시트는 a/b · 파일은 1/2 — ★못 가린다
 *    null      다른 사람
 *
 *  ★★「고객1201 ↔ 고객1202」 를 «같다» 고 하면 동명이인이 서로 뒤바뀐다.
 *    미수를 엉뚱한 사람에게 물리는 자리다. 꼬리가 «둘 다 있고 다르면» 다른 사람이다.
 */
export function 같은사람인가(a, b) {
  const A = 이름다듬기(a), B = 이름다듬기(b);
  if (!A || !B) return null;
  if (A === B) return 꼬리(A) ? '꼬리째' : '민이름';
  const ma = 민이름(A), mb = 민이름(B);
  if (!ma || ma !== mb) return null;
  const ka = 꼬리(A), kb = 꼬리(B);
  if (ka && kb) {
    /** ★둘 다 꼬리가 있는데 다르다 */
    const 숫자a = /^[0-9]+$/.test(ka), 숫자b = /^[0-9]+$/.test(kb);
    return 숫자a === 숫자b ? '꼬리다름' : '꼬리규칙다름';
  }
  return '꼬리한쪽';
}

/** ★붙여도 되나 — 「꼬리다름」 은 ★붙이면 안 된다 */
export const 붙여도되나 = (짝) => 짝 === '꼬리째' || 짝 === '민이름' || 짝 === '꼬리한쪽';
export const 얼마나센가 = (짝) => (짝 === '꼬리째' ? '센것' : 짝 === '꼬리한쪽' ? '꼬리한쪽' : 짝 === '민이름' ? '민이름' : '★못붙임');

/** ★파일 이름에서 사람 이름을 뽑는다 — «꼬리째».
 *
 *  ── ★★꼬리를 살려야 하는 까닭
 *  파일 「190모5683_고객1201_계약서.pdf」 의 「1」 은 군더더기가 아니라
 *  시트 계약자 「고객1201」 과 «같은 꼬리» 다. 지우면 「고객1202」 와 뒤섞인다.
 *  ★직원이 시트와 파일에 «같은 규칙» 을 쓰고 있었다. 나만 지우고 있었다.
 *
 *  ── ★「-1」 「-2」 는 꼬리가 아니라 «장 번호» 다
 *      「정준영3-1.pdf」 「정준영3-2.pdf」  →  둘 다 「정준영3」 의 낱장
 *      「고객1201」 「고객1202」              →  ★서로 다른 사람
 *    그래서 「-숫자」 는 떼고 「이름+숫자」 는 남긴다.
 */
const 성씨 = new Set(('김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구나민진지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용').split(''));
/** ★사람 이름이 «아닌» 말.
 *  ★★칸 이름을 값으로 읽는 일이 잦다 — 실측(2026-08-28): 계약사실확인서에서
 *    「상호」 「추가운전자」 가 계약자 이름으로 잡혔다. 서식의 칸 이름이다.
 *  ★차 이름·우리 사람·법인 이름도 여기 둔다 */
const 안쓰는말 = /^(스위치|프라임|셀렉션|프리패스|계약서|승계|연장|최종|수정|복사|합치기|원본|카니발|그랜저|쏘나타|아반떼|스팅어|레이|모닝|카마로|기블리|투싼|쏘렌토|스파크|티볼리|어벤저|캐스퍼|박영협|고객061|상호|성명|주소|비고|기타|본인|성함|법인명|대표자|임차인|임대인|추가운전자|연대보증인|계약자|보증인|사업자|실거주지|연락처|전화번호|생년월일|면허번호|주민번호|비상연락처|긴급연락처|직장정보|사업장|소재지|차량번호|대여차종|주행거리|보증금|인수자|정비상품|자동차)$/;
const 사람인가 = (v) => /^[가-힣]{2,5}$/.test(v) && 성씨.has(v[0]) && !안쓰는말.test(v);

export function 파일이름에서이름(파일이름) {
  /** ★「-1」 「(2)」 같은 장 번호를 먼저 뗀다. 꼬리는 아직 두고 */
  const n = String(파일이름 ?? '').replace(/\.(pdf|xlsx?|hwp|docx?|jpe?g|png)$/i, '').replace(/[-~]\d+(?=[._\s]|$)/g, '').replace(/~\w{4,}$/, '');
  const 봐 = (홑, 꼬) => (사람인가(홑) ? 홑 + (꼬 ?? '') : '');

  /** 「고객004.pdf」 · 「고객1201.pdf」 — 이름만 (★꼬리를 남긴다) */
  const 홑m = n.trim().match(/^([가-힣]{2,5})([0-9]{1,2}|[a-zA-Z])?$/);
  if (홑m) { const v = 봐(홑m[1], 홑m[2]); if (v) return v; }

  /** 「64고6351_고객013_계약서」 · 「190모5683_고객1201_계약서」 — 차번 바로 뒤 */
  const m1 = n.match(/[0-9]{2,3}[가-힣][0-9]{4}[_\s]+([가-힣]{2,5})([0-9]{1,2}|[a-zA-Z])?(?:[_\s]|$)/);
  if (m1) { const v = 봐(m1[1], m1[2]); if (v) return v; }

  /** 「… 이름[법인]」 — 대괄호 앞 */
  const m2 = n.match(/([가-힣]{2,5})([0-9]{1,2})?\s*[\[(]/);
  if (m2) { const v = 봐(m2[1], m2[2]); if (v) return v; }

  /** 「프라임_정도윤」 — 밑줄 뒤 마지막 토막부터 거슬러 */
  for (const t of n.split(/[_\s]+/).filter(Boolean).reverse()) {
    const tm = t.replace(/[\[\](){}.]/g, '').match(/^([가-힣]{2,5})([0-9]{1,2}|[a-zA-Z])?$/);
    if (tm) { const v = 봐(tm[1], tm[2]); if (v) return v; }
  }
  return '';
}

/** ★사람 이름처럼 생겼나 — 성씨로 시작하고, 서식의 «칸 이름» 이 아니어야 한다 */
export const 사람이름인가 = (v) => {
  const n = 이름다듬기(v).replace(/[0-9a-zA-Z]+$/, '');
  return /^[가-힣]{2,5}$/.test(n) && 성씨.has(n[0]) && !안쓰는말.test(n);
};

/** ★★개인사업자는 «상호» 로 계약하기도 한다 — 대표(2026-08-28)
 *    「**개인사업자는 사업자명을 쓰는 경우가 있어**」
 *
 *  ── ★실측(2026-08-28) 계약사실확인서에서
 *      시트 「전국연합누수119」  ↔  확인서 성명 「고객206」   상호 「전국연합누수119 서울경기점」
 *      시트 「또바기」          ↔  확인서 성명 「방민주」   상호 「또바기」
 *      시트 「광명건설」        ↔  확인서 성명 「고객092」   상호 「광명건설(호성건설중기)」
 *
 *  ★이걸 「이름이 어긋난다」 고 세면 안 된다. «같은 계약» 이다.
 *    사람 이름과 상호를 «둘 다» 담아 두고, 어느 쪽으로도 찾을 수 있게 한다.
 */

/** 상호에서 군더더기를 뗀다 — 「전국연합누수119 서울경기점」 → 「전국연합누수119」 */
export function 상호다듬기(v) {
  return String(v ?? '')
    .replace(/\([^)]*\)/g, '')
    .replace(/\s*(주식회사|㈜|\(주\))\s*/g, '')
    .replace(/\s+(서울|경기|인천|부산|대구|대전|광주|울산|제주|강원|충북|충남|전북|전남|경북|경남)?[가-힣]{0,4}(점|지점|영업소|사업장)$/g, '')
    .replace(/\s+/g, '')
    .trim();
}

/** ★사람 이름 «또는» 상호로 견준다. 어느 쪽으로 맞았는지 말해 준다 */
export function 사람이나상호가같나(a, b, { 상호a = null, 상호b = null } = {}) {
  const 사람 = 같은사람인가(a, b);
  if (사람 && 붙여도되나(사람)) return { 같나: true, 어떻게: `사람 이름 (${사람})` };
  const A = [이름다듬기(a), 상호다듬기(상호a)].filter(Boolean);
  const B = [이름다듬기(b), 상호다듬기(상호b)].filter(Boolean);
  for (const x of A) for (const y of B) {
    if (!x || !y) continue;
    const X = 상호다듬기(x), Y = 상호다듬기(y);
    if (X === Y) return { 같나: true, 어떻게: '★상호가 같다' };
    if (X.length >= 3 && Y.length >= 3 && (X.startsWith(Y) || Y.startsWith(X))) return { 같나: true, 어떻게: '★상호가 겹친다 (지점 표기 차이)' };
  }
  return { 같나: false, 어떻게: null };
}
