/** 작업지킴이 — 예약 작업이 «죽었을 때 사람에게 닿게» 하는 공용 부품
 *
 *  ── 왜 만들었나 (2026-09-16)
 *  이 저장소의 예약 작업은 실패해도 사람에게 닿는 경로가 하나도 없었다. 로그뿐이고
 *  아무도 안 읽는다. `aiops-light` 가 10:10 회차에 0xC000013A(강제종료)로 끊겼는데
 *  아무 알림이 없었다. freepasserp4 에서는 같은 까닭으로 «매시 동기가 사흘 멈춰 있었는데
 *  아무도 몰랐다» — 알림 코드가 작업 «안»에 있어서 작업이 죽을 때 알림도 같이 죽었다.
 *
 *  ── ★그래서 알림은 본체 «밖»에 있다
 *  본체(node)가 강제종료되거나 node 가 뜨지도 못하면 본체 안의 알림도 안 간다.
 *  그래서 알리는 쪽은 «래퍼 .cmd» 다. .cmd 는 node 가 죽어도 다음 줄을 계속 돈다.
 *      node <본체> ...
 *      set RC=%ERRORLEVEL%
 *      node scripts\jikimi-allim.mjs --jageop=... --code=%RC% ...
 *      exit /b %RC%
 *  알림 자체가 또 죽을 수 있으므로(그 node 마저 못 뜨는 경우) 래퍼는 그 «전에»
 *  node 없이 `echo` 로 종료코드 줄을 로그에 박는다. 그 줄은 cmd.exe 만으로 써진다.
 *  그리고 실패를 아무도 못 본 경우까지 잡는 마지막 그물이 아래 「묵었나」다.
 *
 *  ── ★「안 돌았다」는 종료코드로 못 잡는다
 *  작업이 아예 안 뜨면(꺼져 있거나 PC 가 꺼져 있었거나) 종료코드 자체가 없다.
 *  그래서 «마지막 성공 시각»을 맥박 파일 한 곳에 남기고, 그것이 기대 주기를 한참
 *  넘기면 「묵었다」로 본다. 이건 작업과 «다른 프로세스»(scripts/jikimi-jeomgeom.mjs)가
 *  읽는다 — 작업이 한 번도 안 떴어도 지킴이는 뜬다.
 *
 *  ── ★시끄러우면 꺼진다
 *  매번 보내면 사람이 무시한다. 그래서 두 조건 중 하나일 때만 알린다.
 *    (1) 상태가 «바뀌었을» 때 (성공→실패, 실패→성공(복구), 성공→묵음 …)
 *    (2) 같은 실패가 이어져도 «하루 한 번» (한국 날짜 기준)
 *  복구를 알리는 것은, 안 알리면 「그 뒤 어떻게 됐나」를 사람이 로그에서 찾아야 하기
 *  때문이다. 복구는 상태가 바뀔 때 한 번뿐이라 시끄럽지 않다.
 *
 *  ★이 파일의 함수는 파일·네트워크를 만지지 않는 «순수» 함수다. 읽고 쓰는 것은
 *   맥박읽기/맥박쓰기뿐이고, 판단은 전부 순수하다 — 그래야 시험할 수 있다.
 */
