/** 한국 날짜 (YYYY-MM-DD) — 하루 한 번 억제의 기준 */
export const 한국날짜 = (때 = Date.now()) => new Date(때 + 9 * 36e5).toISOString().slice(0, 10);

/** 종료코드 → 상태. ★0 만 성공이다 */
export function 상태보기(코드) {
  const n = Number(코드);
  if (!Number.isFinite(n)) return '모름';
  if (n === 0) return '성공';
  if (n === 6) return '검토대기';
  if (n === 5) return '전환실패';
  return '실패';
}

/** 종료코드를 사람 말로. 겪은 것만 적는다 — 모르면 「모른다」 */
export function 코드풀이(코드) {
  const n = Number(코드);
  if (n === 0) return '성공';
  if (n === 4) return '4 — 파이어스토어 무료 할당량 소진(429)으로 본체가 멈춤';
  if (n === 5) return '5 — 발송대기 전환 과정의 기술 오류';
  if (n === 6) return '6 — 엔진은 완료됐지만 현재 검증판의 독립 검토가 남아 있음';
  // 0xC000013A = 3221225786 (부호 없는 32비트). cmd 는 부호 있는 값으로 넘기기도 한다
  if (n === 3221225786 || n === -1073741510) return '0xC000013A — 강제종료(Ctrl+C·로그오프·전원)';
  if (n === 1) return '1 — 본체가 오류로 끝남';
  if (n === 9009) return '9009 — 명령을 못 찾음(node 가 아예 못 뜬 경우)';
  return `${n} — 무슨 뜻인지 모른다. logs 의 해당 회차를 봐야 한다`;
}

/** ★알릴까 — 순수 함수. 시끄러움 억제가 여기 전부 들어 있다
 *  @param 지난 {상태, 마지막알림날짜} 또는 null(첫 회차)
 *  @returns {알린다:boolean, 까닭:string}
 */
export function 알릴까({ 지난, 상태, 오늘 }) {
  const 앞상태 = 지난?.상태 ?? null;
  if (상태 === '성공') {
    if (앞상태 === null) return { 알린다: false, 까닭: '첫 기록이고 성공 — 조용히 둔다' };
    if (앞상태 === '성공') return { 알린다: false, 까닭: '계속 성공 — 조용히 둔다' };
    return { 알린다: true, 까닭: `${앞상태} → 성공, 상태가 바뀌었다(복구)` };
  }
  // 실패·묵음·모름
  if (앞상태 !== 상태) return { 알린다: true, 까닭: `${앞상태 ?? '기록없음'} → ${상태}, 상태가 바뀌었다` };
  if (지난?.마지막알림날짜 !== 오늘) return { 알린다: true, 까닭: '같은 실패가 이어지지만 오늘은 아직 안 알렸다(하루 한 번)' };
  return { 알린다: false, 까닭: '같은 실패를 오늘 이미 알렸다 — 다시 보내지 않는다' };
}

/** ★묵었나 — 「안 돌았다」 판정. 순수 함수
 *  마지막 성공 시각이 없으면 «모른다»다. 「없다」로 바꾸지 않는다 —
 *  한 번도 안 돈 것과 기록을 잃은 것을 여기서 구별할 수 없기 때문이다.
 */
export function 묵었나({ 마지막성공, 한계시간, 지금 = Date.now() }) {
  if (!마지막성공) return { 묵었다: false, 모른다: true, 까닭: '마지막 성공 기록이 없다 — 한 번도 안 돈 것인지 기록을 잃은 것인지 모른다' };
  const 지난시간 = (지금 - Date.parse(마지막성공)) / 36e5;
  if (!Number.isFinite(지난시간)) return { 묵었다: false, 모른다: true, 까닭: '마지막 성공 시각을 읽을 수 없다' };
  return {
    묵었다: 지난시간 > 한계시간,
    모른다: false,
    지난시간: Math.round(지난시간 * 10) / 10,
    까닭: `마지막 성공에서 ${Math.round(지난시간 * 10) / 10}시간 지났다 (한계 ${한계시간}시간)`,
  };
}

export function 맥박읽기(길 = 맥박길) {
  try { return JSON.parse(fs.readFileSync(길, 'utf8')); } catch { return { 작업: {} }; }
}

export function 맥박쓰기(맥박, 길 = 맥박길) {
  fs.mkdirSync(path.dirname(길), { recursive: true });
  fs.writeFileSync(길, JSON.stringify(맥박, null, 2) + '\n', 'utf8');
}

/** 맥박 한 칸 갱신 — 순수 함수(넣은 것을 고치지 않고 새 것을 돌려준다) */
export function 맥박갱신(맥박, { 작업, 상태, 코드, 때, 때ISO, 알렸나, 오늘 }) {
  const 앞 = 맥박?.작업?.[작업] ?? null;
  // ★마지막성공은 «기계가 다시 읽는» 값이다. 사람이 읽는 「… (KST)」 꼴로 적으면
  //   Date.parse 가 NaN 이 되고 「묵었나」가 영영 「모른다」만 뱉는다 — 시험에서 잡았다.
  //   그래서 여기는 ISO(UTC), 사람이 볼 것은 마지막끝난때 로 나눠 둔다.
  const 성공때 = 때ISO ?? new Date().toISOString();
  const 새 = {
    상태,
    마지막코드: 코드 ?? null,
    마지막끝난때: 때,
    마지막성공: 상태 === '성공' ? 성공때 : (앞?.마지막성공 ?? null),
    마지막성공사람: 상태 === '성공' ? 때 : (앞?.마지막성공사람 ?? null),
    마지막알림날짜: 알렸나 ? 오늘 : (앞?.마지막알림날짜 ?? null),
    마지막알림상태: 알렸나 ? 상태 : (앞?.마지막알림상태 ?? null),
  };
  return { ...맥박, 적은때: 때, 작업: { ...(맥박?.작업 ?? {}), [작업]: 새 } };
}

/** 알림 글 — 제목과 본문. ★숫자를 지어내지 않는다. 아는 것만 적는다 */
export function 알림글({ 작업, 상태, 코드, 때, 까닭, 덧붙임 = [] }) {
  const 이름 = 작업표[작업]?.무엇 ?? '(표에 없는 작업)';
  const 제목 = 상태 === '성공'
    ? `[aiops] 작업 복구 — ${작업}`
    : `[aiops] 작업 ${상태} — ${작업}`;
  const 줄 = [
    `예약 작업 ${상태}`,
    '',
    `작업   ${작업}  (${이름})`,
    `시각   ${때}`,
    상태 === '묵음' ? '종료코드  없음 — 성공 기록이 묵었다 (안 떴거나, 떴다가 실패했거나)' : `종료코드  ${코드 ?? '모름'}  ${코드 == null ? '' : `(${코드풀이(코드)})`}`,
    '',
    ...덧붙임,
    '',
    '무엇을 보나',
    '  logs\\daily.log · logs\\gwataeryo-achim.log 의 해당 회차',
    '  logs\\jikimi-maekbak.json (마지막 성공 시각)',
    '  docs\\aiknowhow\\자동화.md KH-019 「작업이 죽었을 때 어떻게 알게 되나」',
    '',
    `※ 같은 상태가 이어지면 하루 한 번만 보냅니다. (이번에 보낸 까닭: ${까닭})`,
    '— aiops 작업지킴이',
  ];
  return { 제목, 본문: 줄.join('\n') };
}
