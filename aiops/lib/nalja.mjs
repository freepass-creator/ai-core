/** ★★날짜 — 두 자리 연도 함정을 한 자리에서 막는다.
 *
 *  ── ★★엑셀은 「30」 을 «1930년» 으로 읽는다
 *  손오공 「채권」 탭에서 이런 줄이 73개 나왔다:
 *
 *      2026-06-04  ~  1930-06-03
 *      2026-08-28  ~  1930-08-27
 *      2026-01-27  ~  1930-01-26
 *
 *  ★종료가 시작보다 «96년 앞» 이다. 그럴 리가 없다.
 *  ★월·일을 보면 «시작 −1일» 이다. 즉 원래는 「시작 + 4년 − 1일」 —
 *    사람이 「30-06-03」 이라 적은 것을 엑셀이 1930년으로 새긴 것이다. 실제는 **2030년**.
 *
 *  ── ★어떻게 고치나
 *  ★함부로 다 더하지 않는다. 「1988-03-02」 같은 «진짜 옛 날짜»(생년월일 등)도 있다.
 *  ★고치는 조건은 하나다 — «그 날짜가 짝이 되는 날짜보다 앞» 일 때만.
 *    계약 종료가 시작보다 앞일 수는 없다. 그때만 100년을 더한다.
 *
 *  ── ★고쳤다는 것을 «남긴다»
 *  조용히 고치면 다음 사람이 「왜 2030이지?」 하고 또 뒤진다.
 *  ★고친 자리에 표를 남겨 근거를 남긴다.
 */

/** 「2026-06-04」 꼴인가 */
const 날꼴 = /^(\d{4})-(\d{2})-(\d{2})$/;

/** ★두 자리 연도가 1900년대로 새겨진 것을 되돌린다.
 *  @param 값     고칠 날짜 (보통 «종료일»)
 *  @param 기준   그보다 앞설 수 없는 날짜 (보통 «시작일»)
 *  @returns {날, 고쳤나, 왜}
 */
export function 두자리연도되돌리기(값, 기준) {
  const s = String(값 ?? '');
  const m = s.match(날꼴);
  if (!m) return { 날: 값 ?? null, 고쳤나: false, 왜: null };
  const 해 = Number(m[1]);
  /** ★1900년대가 아니면 손대지 않는다 */
  if (해 < 1900 || 해 > 1999) return { 날: s, 고쳤나: false, 왜: null };
  /** ★기준이 없으면 못 고친다 — 「모른다」 로 둔다. 짐작으로 100년을 더하지 않는다 */
  if (!기준 || !날꼴.test(String(기준))) return { 날: s, 고쳤나: false, 왜: '★1900년대인데 견줄 날짜가 없다 — 모른다' };
  /** ★기준보다 앞설 수 없는 자리인데 앞서 있다 → 두 자리 연도가 깨진 것이다 */
  if (s >= String(기준)) return { 날: s, 고쳤나: false, 왜: null };
  const 새 = `${해 + 100}-${m[2]}-${m[3]}`;
  return {
    날: 새,
    고쳤나: true,
    왜: `★엑셀이 두 자리 연도를 1900년대로 새겼다 (${s} → ${새}). 시작 ${기준} 보다 앞설 수 없다`,
  };
}

/** ★★대표가 못박았다 (2026-08-28): 「**1930년은 2030이야 정제하고**」
 *
 *  ★위 함수는 «기준 날짜가 있을 때만» 고친다. 기준이 없는 자리(원장·요약)에서는
 *    못 고치고 1930 이 그대로 남는다.
 *  ★대표가 확정했으니 1930년대·1931년대는 그냥 100년을 더한다.
 *    렌터카 계약에 1930년이 있을 리 없다.
 *  ★단 1900~1929 는 손대지 않는다 — 그건 아래 「1900-01-25」 갈래다. */
export function 년대정제(값) {
  const s = String(값 ?? '');
  const m = s.match(날꼴);
  if (!m) return { 날: 값 ?? null, 고쳤나: false };
  const 해 = Number(m[1]);
  if (해 < 1930 || 해 > 1999) return { 날: s, 고쳤나: false };
  return { 날: `${해 + 100}-${m[2]}-${m[3]}`, 고쳤나: true, 왜: `★두 자리 연도 함정 — ${해} 는 ${해 + 100} 이다 (대표 확정)` };
}

/** ★★「1900-01-25」 는 «날짜» 가 아니라 «25일» 이다 — 다른 함정
 *
 *  손오공 「채권」 탭 「결제일」 칸에는 「05일」 · 「25일」 · 「말일」 이 적혀 있다.
 *  ★어떤 줄은 글자로, 어떤 줄은 엑셀이 «날짜» 로 새겼다 —
 *    「25」 를 1900년 1월 25일로 읽은 것이다. 엑셀의 날짜 0 이 1900-01-00 이라서다.
 *  ★그래서 payment_record 「약정일」 338곳에 「1900-01-25 00:00:00」 이 들어 있었다.
 *    이걸 날짜로 두면 「1900년에 낸 돈」 이 되고, 미수 셈이 통째로 어긋난다.
 *
 *  ★1900-01-<날> → 「<날>」 로 되돌린다. 이건 «달의 며칠» 이다. */
export function 약정일정제(값) {
  const s = String(값 ?? '').trim();
  if (!s) return { 값: null, 고쳤나: false };
  const m = s.match(/^1900-01-(\d{2})/);
  if (m) return { 값: String(Number(m[1])), 고쳤나: true, 왜: '★「1900-01-25」 는 날짜가 아니라 «25일» 이다 (엑셀이 며칠을 날짜로 새겼다)' };
  /** 「05일」 · 「25일」 → 「5」 · 「25」 · 「말일」 은 그대로 */
  const m2 = s.match(/^(\d{1,2})\s*일$/);
  if (m2) return { 값: String(Number(m2[1])), 고쳤나: true, 왜: '「05일」 → 「5」' };
  return { 값: s, 고쳤나: false };
}

/** ★계약 한 줄을 통째로 고친다 — 시작·종료·반납 */
export function 계약날짜바로잡기(줄, { 시작칸 = '시작', 종료칸 = '종료', 반납칸 = '반납' } = {}) {
  const 고친것 = [];
  const 시작 = 줄[시작칸];
  for (const 칸 of [종료칸, 반납칸]) {
    if (!줄[칸]) continue;
    const r = 두자리연도되돌리기(줄[칸], 시작);
    if (r.고쳤나) { 줄[칸] = r.날; 고친것.push(`${칸}: ${r.왜}`); }
  }
  return { 줄, 고친것 };
}
